import Foundation

enum JamfProAuthMode: String, CaseIterable, Identifiable {
    case usernamePassword = "Username + Password"
    case apiClient = "API Client ID + Secret"

    var id: String { rawValue }
}

struct JamfProUploadSummary {
    let profileName: String
    let endpoint: URL
    let responseCode: Int
}

enum JamfProUploadError: LocalizedError {
    case invalidURL
    case httpsRequired
    case missingCredentials(String)
    case noSettingsFound
    case invalidResponse
    case authFailed(statusCode: Int, body: String)
    case uploadFailed(statusCode: Int, body: String)

    var errorDescription: String? {
        switch self {
        case .invalidURL:
            return "Enter a valid Jamf Pro URL."
        case .httpsRequired:
            return "Only HTTPS URLs are allowed for Jamf Pro."
        case .missingCredentials(let message):
            return message
        case .noSettingsFound:
            return "No JamfAAD settings were found to upload."
        case .invalidResponse:
            return "Jamf Pro returned an invalid response."
        case .authFailed(let code, let body):
            return "Authentication failed (\(code)). \(body)"
        case .uploadFailed(let code, let body):
            return "Upload failed (\(code)). \(body)"
        }
    }
}

struct JamfProUploader {
    private static let jamfDomain = "com.jamf.management.jamfAAD"

    static func upload(
        baseURL: String,
        authMode: JamfProAuthMode,
        username: String,
        password: String,
        clientID: String,
        clientSecret: String,
        profileName: String
    ) async throws -> JamfProUploadSummary {
        let trimmedURL = baseURL.trimmingCharacters(in: .whitespacesAndNewlines)
        guard var normalized = URL(string: trimmedURL) else {
            throw JamfProUploadError.invalidURL
        }

        if normalized.scheme == nil {
            guard let withHTTPS = URL(string: "https://\(trimmedURL)") else {
                throw JamfProUploadError.invalidURL
            }
            normalized = withHTTPS
        }

        guard normalized.scheme?.lowercased() == "https" else {
            throw JamfProUploadError.httpsRequired
        }

        let settings = readJamfAADSettingsExcludingLogPII()
        guard !settings.isEmpty else {
            throw JamfProUploadError.noSettingsFound
        }

        let cleanedName = profileName.trimmingCharacters(in: .whitespacesAndNewlines)
        if cleanedName.isEmpty {
            throw JamfProUploadError.missingCredentials("Profile name cannot be empty.")
        }
        let cleanedDescription = "Generated by Device Compliance Troubleshooter"

        let payloadData = try buildMobileConfigData(
            settings: settings,
            displayName: cleanedName,
            description: cleanedDescription
        )
        let payloadXML = String(decoding: payloadData, as: UTF8.self)
        let xmlBody = makeClassicAPIXML(
            profileName: cleanedName,
            profileDescription: cleanedDescription,
            payloadXML: payloadXML
        )

        let authHeader: String
        switch authMode {
        case .usernamePassword:
            let cleanedUsername = username.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !cleanedUsername.isEmpty, !password.isEmpty else {
                throw JamfProUploadError.missingCredentials("Username and password are required.")
            }
            authHeader = try await bearerToken(
                baseURL: normalized,
                username: cleanedUsername,
                password: password
            )
        case .apiClient:
            let cleanedClientID = clientID.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !cleanedClientID.isEmpty, !clientSecret.isEmpty else {
                throw JamfProUploadError.missingCredentials("API Client ID and Secret are required.")
            }
            authHeader = try await bearerToken(
                baseURL: normalized,
                clientID: cleanedClientID,
                clientSecret: clientSecret
            )
        }

        let uploadURL = normalized.appending(path: "JSSResource/osxconfigurationprofiles/id/0")
        do {
            var request = URLRequest(url: uploadURL)
            request.httpMethod = "POST"
            request.httpBody = Data(xmlBody.utf8)
            request.setValue("application/xml", forHTTPHeaderField: "Content-Type")
            request.setValue("application/xml", forHTTPHeaderField: "Accept")
            request.setValue(authHeader, forHTTPHeaderField: "Authorization")

            let (data, response) = try await URLSession.shared.data(for: request)
            guard let http = response as? HTTPURLResponse else {
                throw JamfProUploadError.invalidResponse
            }

            if !(200...299).contains(http.statusCode) {
                let body = sanitizeResponseBody(data)
                throw JamfProUploadError.uploadFailed(statusCode: http.statusCode, body: body)
            }

            let summary = JamfProUploadSummary(
                profileName: cleanedName,
                endpoint: uploadURL,
                responseCode: http.statusCode
            )
            try? await invalidateBearerToken(baseURL: normalized, authHeader: authHeader)
            return summary
        } catch {
            try? await invalidateBearerToken(baseURL: normalized, authHeader: authHeader)
            throw error
        }
    }

    static func readJamfAADSettingsExcludingLogPII() -> [String: Any] {
        // Pull the most up-to-date values from the preferences domain first.
        CFPreferencesAppSynchronize(jamfDomain as CFString)

        var dictionary = UserDefaults.standard.persistentDomain(forName: jamfDomain) ?? [:]

        dictionary.removeValue(forKey: "logPII")

        return dictionary.reduce(into: [:]) { result, pair in
            if isPropertyListSafe(pair.value) {
                result[pair.key] = pair.value
            }
        }
    }

    static func settingsPlistPreview() -> String {
        let settings = readJamfAADSettingsExcludingLogPII()
        guard !settings.isEmpty else {
            return ""
        }

        do {
            let data = try PropertyListSerialization.data(
                fromPropertyList: settings,
                format: .xml,
                options: 0
            )
            return String(decoding: data, as: UTF8.self)
        } catch {
            return "Failed to render plist preview: \(error.localizedDescription)"
        }
    }

    private static func bearerToken(baseURL: URL, clientID: String, clientSecret: String) async throws -> String {
        let tokenURL = baseURL.appending(path: "api/oauth/token")
        var request = URLRequest(url: tokenURL)
        request.httpMethod = "POST"
        request.setValue("application/x-www-form-urlencoded", forHTTPHeaderField: "Content-Type")
        request.setValue("application/json", forHTTPHeaderField: "Accept")

        var form = URLComponents()
        form.queryItems = [
            URLQueryItem(name: "client_id", value: clientID),
            URLQueryItem(name: "grant_type", value: "client_credentials"),
            URLQueryItem(name: "client_secret", value: clientSecret)
        ]
        request.httpBody = form.percentEncodedQuery?.data(using: .utf8)

        let (data, response) = try await URLSession.shared.data(for: request)
        guard let http = response as? HTTPURLResponse else {
            throw JamfProUploadError.invalidResponse
        }

        guard (200...299).contains(http.statusCode) else {
            let body = sanitizeResponseBody(data)
            throw JamfProUploadError.authFailed(statusCode: http.statusCode, body: body)
        }

        let tokenResponse = try JSONDecoder().decode(TokenResponse.self, from: data)
        return "Bearer \(tokenResponse.accessToken)"
    }

    private static func bearerToken(baseURL: URL, username: String, password: String) async throws -> String {
        let tokenURL = baseURL.appending(path: "api/v1/auth/token")
        var request = URLRequest(url: tokenURL)
        request.httpMethod = "POST"
        request.setValue("application/json", forHTTPHeaderField: "Accept")
        request.setValue("Basic \(base64("\(username):\(password)"))", forHTTPHeaderField: "Authorization")

        let (data, response) = try await URLSession.shared.data(for: request)
        guard let http = response as? HTTPURLResponse else {
            throw JamfProUploadError.invalidResponse
        }

        guard (200...299).contains(http.statusCode) else {
            let body = sanitizeResponseBody(data)
            throw JamfProUploadError.authFailed(statusCode: http.statusCode, body: body)
        }

        let tokenResponse = try JSONDecoder().decode(UserPassTokenResponse.self, from: data)
        return "Bearer \(tokenResponse.token)"
    }

    private static func invalidateBearerToken(baseURL: URL, authHeader: String) async throws {
        let invalidateURL = baseURL.appending(path: "api/v1/auth/invalidate-token")
        var request = URLRequest(url: invalidateURL)
        request.httpMethod = "POST"
        request.setValue("application/json", forHTTPHeaderField: "Accept")
        request.setValue(authHeader, forHTTPHeaderField: "Authorization")
        _ = try await URLSession.shared.data(for: request)
    }

    private static func buildMobileConfigData(settings: [String: Any], displayName: String, description: String) throws -> Data {
        let profileUUID = UUID().uuidString
        let payloadUUID = UUID().uuidString

        let managedPayload: [String: Any] = [
            "PayloadType": "com.apple.ManagedClient.preferences",
            "PayloadVersion": 1,
            "PayloadIdentifier": "com.devicecompliance.jamfaad.managed.\(payloadUUID)",
            "PayloadDisplayName": "JamfAAD Preferences",
            "PayloadContent": [
                jamfDomain: [
                    "Forced": [
                        [
                            "mcx_preference_settings": settings
                        ]
                    ]
                ]
            ]
        ]

        let rootProfile: [String: Any] = [
            "PayloadType": "Configuration",
            "PayloadVersion": 1,
            "PayloadIdentifier": "com.devicecompliance.jamfaad.profile.\(profileUUID)",
            "PayloadUUID": profileUUID,
            "PayloadDisplayName": displayName,
            "PayloadDescription": description,
            "PayloadEnabled": true,
            "PayloadScope": "System",
            "PayloadRemovalDisallowed": true,
            "PayloadContent": [managedPayload]
        ]

        return try PropertyListSerialization.data(
            fromPropertyList: rootProfile,
            format: .xml,
            options: 0
        )
    }

    private static func makeClassicAPIXML(profileName: String, profileDescription: String, payloadXML: String) -> String {
        let escapedName = xmlEscaped(profileName)
        let escapedDescription = xmlEscaped(profileDescription)
        let escapedPayloadXML = xmlEscaped(payloadXML)

        return """
<?xml version=\"1.0\" encoding=\"UTF-8\"?>
<os_x_configuration_profile>
  <general>
    <name>\(escapedName)</name>
    <distribution_method>Install Automatically</distribution_method>
    <user_removable>false</user_removable>
    <level>System</level>
    <payloads>\(escapedPayloadXML)</payloads>
  </general>
</os_x_configuration_profile>
"""
    }

    private static func base64(_ text: String) -> String {
        Data(text.utf8).base64EncodedString()
    }

    /// Sanitizes API response body for safe display: truncates length and strips content that might leak sensitive data.
    private static func sanitizeResponseBody(_ data: Data) -> String {
        let maxLength = 500
        let raw = String(data: data, encoding: .utf8)?
            .trimmingCharacters(in: .whitespacesAndNewlines)
            .components(separatedBy: .newlines)
            .joined(separator: " ")
        guard let raw, !raw.isEmpty else {
            return "No response body"
        }
        let stripped = raw
            .replacingOccurrences(of: "<[^>]+>", with: " ", options: .regularExpression)
            .replacingOccurrences(of: "\\s+", with: " ", options: .regularExpression)
            .trimmingCharacters(in: .whitespaces)
        if stripped.count <= maxLength {
            return stripped
        }
        return String(stripped.prefix(maxLength)) + "…"
    }

    private static func xmlEscaped(_ text: String) -> String {
        text
            .replacingOccurrences(of: "&", with: "&amp;")
            .replacingOccurrences(of: "<", with: "&lt;")
            .replacingOccurrences(of: ">", with: "&gt;")
            .replacingOccurrences(of: "\"", with: "&quot;")
            .replacingOccurrences(of: "'", with: "&apos;")
    }

    private static func isPropertyListSafe(_ value: Any) -> Bool {
        switch value {
        case is String, is Int, is Double, is Float, is Bool, is Date, is Data:
            return true
        case let array as [Any]:
            return array.allSatisfy(isPropertyListSafe)
        case let dictionary as [String: Any]:
            return dictionary.values.allSatisfy(isPropertyListSafe)
        default:
            return false
        }
    }
}

private struct TokenResponse: Decodable {
    let accessToken: String

    enum CodingKeys: String, CodingKey {
        case accessToken = "access_token"
    }
}

private struct UserPassTokenResponse: Decodable {
    let token: String
}
